    /// <summary>卡尺射线数。</summary>
    public int PinCaliperRays { get; set; } = 180;

    /// <summary>
    /// 灰圆（极柱端面）半径的**族值**（× base）——灰圆自身测量的尺度基准。
    ///
    /// 为什么需要它：改动前灰圆的搜索窗、平滑尺度、离群门限全部取自**焊环半径**，
    /// 于是焊环一旦被外围反光细圈带偏，灰圆的搜索窗整片搬到无关区域，产生误差级联
    /// （实测 Img000：焊环圆心偏 202.6px，灰圆随之错，偏移量报 0.396mm 而真值约 0.81mm）。
    /// 现在灰圆的全部尺度改用本项 × base，**与焊环半径无关**，两个地标各自独立测量。
    ///
    /// 实测依据：工作分辨率下灰圆半径实测约 21.8px ÷ base 460 ≈ **0.047**。
    /// 本项只作尺度基准（搜索窗/平滑/门限），**不作判据**——判据见
