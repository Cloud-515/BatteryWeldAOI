    /// 但那批数字全部来自**梯度卡尺**的输出，而卡尺的射线原点是焊环圆心——孔心一旦偏离焊环圆心
    /// （本产品实测偏离约 0.3×焊环半径），卡尺抓到的是熔核内沿，量出的半径约为真值的两倍。
    /// 孔位改由 <see cref="Vision.HoleLocator"/> 的三材质分层给出后（见
