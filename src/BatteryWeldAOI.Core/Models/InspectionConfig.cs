    /// 降级为中间层结果。
    /// </summary>
    public double MaxPinArcRadiusRatioOfRing { get; set; } = 0.30;

    /// <summary>正弦拟合残差上限（× 焊环半径）。残差大说明射线没有一致地落在同一个圆上，
