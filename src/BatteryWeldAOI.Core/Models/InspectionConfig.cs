    /// `dualScaleGate`）。
    ///
    /// **为什么需要它（2026-09-17 新增，修用户报的"红圈仍然偏移"）**：熔核外面常常还有一圈
    /// **细密的灰斑噪声带**（表面污渍 / 环形光反射的散斑），它在小窗能量图上同样"粗糙"，
    /// 于是被并进掩码。实测某一帧：纹理密度的径向剖面 φ(r) 到 r=66 个工作像素还是 0.95，
