    /// 而它们的圆心是对的（标注图核对过）——只是掩码取的是孔位端面**被照亮的那一部分**，
    /// 拟合半径系统性偏小约 20~30%（详见 <see cref="MinHoleFitResidualPx"/> 的注记）。
    /// 取 0.10 与 <see cref="MinHoleRadiusRatio"/> 取齐：孔位路径下两者本就是对同一个数的两次检查，
