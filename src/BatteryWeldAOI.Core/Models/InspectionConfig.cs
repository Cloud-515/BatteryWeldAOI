namespace BatteryWeldAOI.Core.Models;

/// <summary>
/// 检测系统全局配置。
/// 属性为可写（非 init），以支持 JSON 配置文件序列化与界面双向绑定。
/// </summary>
public sealed class InspectionConfig
{
    /// <summary>
    /// 相机横向分辨率（像素）。**这是标定坐标系的分辨率，不是输入图片的分辨率。**
    ///
    /// 毫米换算按 "本值 ÷ 实际图幅" 得到**单一等比系数**，再用它把输入图像素换算到标定坐标系
    /// （见 WeldInspectionAlgorithm.ToMillimetres），其含义是"输入图 = 整幅配置视野的一个缩放版本"。
    ///
    /// **视野宽度由 <see cref="MmPerPixel"/> 决定：1280 × 0.1003 = 128.4mm**（2026-09-17 现场实测
    /// 重新标定，见该属性）。旧注释里"由 32mm × (焊环半径px ÷ 图宽px)"那套反推已作废——
    /// 32mm 是个错误假设，它使焊环物理半径被算成 3.9~6.2mm，真值是 **24.3~25.0mm 直径**
    /// （按 0.0235 mm/原图像素 × 0.142~0.146×3648px）。
    ///
    /// **两轴必须共用同一系数**。曾经按 X/Y 分轴折算，那是缺陷：宽高比不一致时同一段物理距离
    /// 在 X/Y 上会被折成不同的毫米数（实测配置 1280×1024 跑 5472×3648 的图，两轴系数 1.855 vs 2.226，
    /// 差 20%，即偏移量的**方向**被歪曲 20%，而 1.0mm 公差判定就建立在这个合成值上）。
    /// 由于该系数是各向同性的，且工作图是原图的长宽等比缩小，X/Y 的毫米当量必然相等
    /// ——**宽高比偏差只影响"本配置是否就是该相机的真实分辨率"这一判断，不影响毫米读数的正确性**。
    ///
    /// 本值（1280×1024，宽高比 1.25）与现场相机（5472×3648，宽高比 1.50）的宽高比仍不一致，
    /// 因此 <see cref="FovAspectDeviation"/> 仍会报 0.20。这是**已知的声明口径差异**：
    /// 1280×1024 现在是"标定坐标系 + 合成演示图的渲染尺寸"（合成夹具的原生尺度就是它，
    /// 见 tests 的 0.025mm/px 夹具），不是现场相机的分辨率。要做正式标定时，
    /// 应把这三个值一起改成相机的真实值（5472×3648 @ 0.0235mm/px），届时本项会归零。
    /// </summary>
    public int ImageWidth { get; set; } = 1280;

    /// <summary>相机纵向分辨率（像素）。与 <see cref="ImageWidth"/> 一同参与毫米折算，说明见该属性。</summary>
    public int ImageHeight { get; set; } = 1024;

    /// <summary>
    /// 输入图与配置视野的**宽高比偏差**（0 = 一致；0.20 = 差 20%）。
    ///
    /// 返回值的量纲正是"配置不匹配会带来多大的轴向误差"，等于
    /// <c>|ImageWidth·图高 − ImageHeight·图宽| ÷ (ImageWidth·图高)</c>。
    /// 实测配置 1280×1024 跑 5472×3648 现场图返回 0.20，与旧版分轴折算的两轴系数之比
    /// 2.226/1.855 = 1.20 完全一致。
    ///
    /// 用法：不为 0 即说明配置分辨率不是该相机的真实值，此时毫米数值的**绝对尺度不可信**
    /// （检测判定用的是尺度相对量，不受影响）。应当在界面上提示操作员并实测标定后修正配置。
    /// </summary>
    public double FovAspectDeviation(int imageWidth, int imageHeight)
    {
        if (imageWidth <= 0 || imageHeight <= 0)
            return 0;
        var reference = (double)ImageWidth * imageHeight;
        return Math.Abs(reference - (double)ImageHeight * imageWidth) / reference;
    }

    /// <summary>
    /// 检测所用的最大工作边（像素）。输入图短边超过本值时，算法先把它**等比缩小**到本值再检测。
    ///
    /// **为什么必须归一化**：本类所有视觉参数都是相对量（分母 base = min(高,宽)），
    /// 但实现里几个形态学核带**绝对像素上限**——纹理窗 ≤15px、闭运算核 ≤21px、开运算核 ≤15px、
    /// 飞溅开运算核 ≤9px（见 WeldRingLocator / WeldQualityMeter 中的 Geo.Odd 调用）。
    /// 比例系数决定"核应有多大"，上限决定"核最大只能是多大"，两者在 base 超过约 460px 后开始打架：
    /// 0.045×base 在 base=3648 时本应是 164px，实际被钳到 21px，相对尺度差 7.8 倍。
    /// 后果不是"精度略降"而是**整条链路失效**：闭运算桥接不到鱼鳞斑、开运算删不掉极板噪点，
    /// 实测 2025-09-11 现场图（5472×3648，SN_CCSAGZZG01A2536925090900002025080700034）
    /// **24/24 全部被误判为飞溅 NG**，D 报 0.295mm 均值；归一化到 460px 后 22/24 判合格，
    /// D 均值降到 0.035mm，单点耗时也从 1.6s 降到 0.07s（大核形态学正是耗时主因：
    /// 164px 椭圆核闭运算在 20MP 上要 18.5s，21px 只要 0.28s）。
    ///
    /// 取 460 而不是更大：0.045×460 = 20.7 → 21px，恰好不触发闭运算核的 21px 上限，
    /// 即本值保证"所有核都按比例取到、一个上限都不生效"。要调大本值，必须同时放宽那几个上限，
    /// 否则相对参数会在新的阈值处再次失真。
    ///
    /// 副作用：缩小会损失测量精度（1mm 公差在大图上约合 100px，归一化后约 12px），
    /// 但这与 tests/tp 那批现场图（182~508px）本就处于同一量级，不影响判据为 1mm 的合格判定。
    /// 设为 0 表示不做归一化（保留原行为，仅用于对照实验）。
    /// </summary>
    public int MaxWorkingBase { get; set; } = 460;

    /// <summary>
    /// 像素当量（毫米/标定坐标系像素）。当提供九点标定时以标定结果为准。
    /// 本值是**标定坐标系**（<see cref="ImageWidth"/>×<see cref="ImageHeight"/>）下的当量；
    /// 换算到其他尺寸的图会按"配置宽 ÷ 实际图宽"得到单一等比系数再折算。
    ///
    /// **2026-09-17 由现场实测重新标定：0.025 → 0.1003。**
    /// 用户带卡尺到现场量了两个工件上的实物尺寸：凹陷圆环（焊环外那条细暗圈）直径 **30mm**、
    /// 孔直径 **5mm**，二者同心（孔在凹陷中心）。用前者定标：
    ///   · 该圆环在图上直径 1278 原图像素（半径 639.2px）；
    ///   · 先验证过标注图裁剪与现场 JPEG 是 1:1（低质量 JPEG 的 8×8 块边界自相关在滞后 8 处
    ///     0.96，与现场原图自身对照的 0.98 同样尖锐；非整数倍缩放会把这个峰抹平）——
    ///     所以 1278px 就是原图像素；
    ///   · 即 42.6 原图像素/mm → **0.0235 mm/原图像素**。
    /// 本字段所在的标定坐标系宽 <see cref="ImageWidth"/>=1280，而现场图宽 5472，
    /// 折算系数 = 1280/690（工作图宽）= 1.855，故本值需为 0.0235 × 5472 / 1280 = **0.1003**，
    /// 使 视野宽 = 1280 × 0.1003 = **128.4mm**（实测 30mm 圆环占图宽 23.4% → 128mm，吻合）。
    ///
    /// 旧的 0.025（配 1280 宽 → 视野 32mm）使**所有毫米读数偏小 4.01 倍**：现场图上一个真实的
    /// 1mm 偏移报成 0.249mm，于是 1.0mm 公差物理上等于 4.0mm。这是"该判 NG 却判合格"的量级来源，
    /// 也是本轮修正的直接原因。20 SN / 480 帧厂商良品的偏移量就此从"中位 0.496mm"变为
    /// **"中位 1.99mm"**（详见 <see cref="OffsetToleranceMm"/>）。
    ///
    /// **仍未做正式九点标定**：本值来自"一个实物尺寸 + 图幅比例"，只保证**尺度**正确，
    /// 不含镜头畸变、不含相机安装偏角（后者由 <see cref="Planning.DemoPlanBuilder"/> 的
    /// 0.6° 仿射占位）。上机前仍应走标准流程：平台带标定板走九点 → 用已知尺寸复核。
    /// </summary>
    public double MmPerPixel { get; set; } = 0.1003;

    /// <summary>
    /// 焊偏判定公差（毫米），合成偏移超过即判 NG。**可在界面上直接改**（"焊偏公差 mm" 输入框，
    /// 与 config.json 双向持久化，运行中锁定），供工艺给出正式值后替换。
    ///
    /// **2026-09-17 按 pp 参考集重定：1.0 → 6.6。** 用户要求"按 pp 里的那些作为正确参考"，
    /// 即由厂商判良品的那批现场图定义"可接受"。实测口径与结果：
    ///   · 参考集：tests/pp 前 20 个 SN / **480 帧，全部厂商 OK**（`tools/VdbImport agree` 全量跑）；
    ///   · 按修正后的当量（<see cref="MmPerPixel"/> = 0.1003，即 0.0235 mm/原图像素）实测偏移量：
    ///     min 0.198、p10 1.070、p25 1.472、**中位 1.989**、p75 2.649、p90 3.780、p95 4.091、
    ///     p99 4.793、**max 5.763**（mm）；
    ///   · 取"良品最大值 × 1.15" = **6.6mm**（与本类既有的"良品最大值外推"口径一致，
    ///     见 <see cref="BlowoutRingRadiusRatio"/> 的 1.25 倍外推）。
    ///
    /// **这个数值必须被理解为"筛查限"，不是工艺规格**：
    ///   · 它只保证"厂商判过的良品不会被误判"，代价是**只能抓明显离谱的偏移**——6.6mm 相对
    ///     熔核半径 12.4mm 是 53%，即偏移到熔核边缘附近才算超差。若工艺给的值比它小得多
    ///     （大概率如此），现场立刻会出现大量 NG，那是**正确行为**（说明现在这批零件的焊偏
    ///     确实超出工艺要求），不该回头放宽公差。
    ///   · 反过来说，pp 这批良品在**修正当量后**的偏移量中位数就是 2.0mm、p90 3.8mm——
    ///     同一批零件在修正前只要 0.5mm（旧当量），这个 4 倍差正是标定修正带来的。
    ///     **尚未定论**的是这些偏移到底是真的偏心（那工艺公差就该是毫米级）、还是"熔核中心"
    ///     这个量被形状带偏（实测该帧的粗糙熔核区是新月形、质心有 3.5mm 的形状偏移，
    ///     而孔心与凹陷圆环心只差 0.12mm，说明基准侧没问题）。分辨办法是统计偏移的**方向**：
    ///     随机分布 = 真偏心；聚在固定方向 = 测量偏置。此项待做，结论出来前不要把 6.6mm 当成工艺值。
    ///
    /// **可测域提醒**：正弦卡尺模型只在 D &lt; 0.8×孔半径 时可靠。孔半径实测 ≈ 0.227×熔核半径
    /// ≈ 2.8mm（按 0.0235 mm/原图像素），即可测上限 ≈ 2.2mm——而参考集 p90 已 3.8mm，
    /// 也就是说**卡尺兜底路径在这批数据上大半落在可靠域之外**（会给出偏小的读数）。
    /// 主路径已改用 <see cref="Vision.HoleLocator"/> 的三材质分层，不依赖该模型；
    /// 这条限制只对"分层失败后退回卡尺"的少数帧成立。
    /// </summary>
    public double OffsetToleranceMm { get; set; } = 6.6;

    // ==================================================================================
    //  视觉参数一律以「尺度相对量」表达：分母 base = min(图像高, 图像宽)。
    //  这样同一套参数对任意分辨率、任意相机都成立——换镜头/改分辨率不需要重新标参数，
    //  这是本算法与旧版（绝对像素阈值，只在合成图上成立）最根本的区别。
    //  比例值由 27 个真实良品样本的统计分布给出，并在良品分布外留出物理余量。
    // ==================================================================================

    // ---- 焊环（焊点熔核）检测：纹理能量分割 ----
    /// <summary>纹理能量窗口边长（× base）。取值需大于单个鱼鳞斑、小于焊环直径。</summary>
    public double TextureWindowRatio { get; set; } = 0.030;

    /// <summary>焊环二值化阈值系数 k：thr = median(E) + k·(p99(E) − median(E))。
    /// 用分位数而非绝对灰度，对曝光/增益变化免疫。</summary>
    public double TextureThresholdK { get; set; } = 0.25;

    /// <summary>图像边框禁区宽度（× base）。贴边的连通域视为背景/台面边缘而剔除。</summary>
    public double BorderMarginRatio { get; set; } = 0.050;

    /// <summary>
    /// 闭运算核边长（× base），桥接鱼鳞斑之间的缝隙。
    /// 与 <see cref="PreOpenKernelRatio"/> 配合：先删细线，再桥接，见后者的说明。
    /// </summary>
    public double CloseKernelRatio { get; set; } = 0.045;

    /// <summary>
    /// 闭运算**之前**的开运算核边长（× base），用于删除薄结构（细线、薄环）。
    ///
    /// 为什么需要这一步：环形光源在工件上的反射、激光打标细圈这类特征会在纹理能量图上
    /// 形成一条十几像素厚的带。它若紧贴熔核外沿，后续闭运算会把两者桥接成**一个实心圆盘**，
    /// 此后任何形状统计量都分辨不出来——实测 2025-09-11 现场图（5472×3648，归一化到 460px）
    /// 并块后圆度 0.99、填洞前后面积完全相同，圆盘半径比熔核本体大 35%。
    /// 后果是每张 SN 的 24 帧里稳定有 1~2 帧被判**漏焊 NG**（伪造的缺陷，不是测量失败）。
    /// 放在闭运算**之前**是关键：闭运算一旦桥接，再开运算就切不开了。
    ///
    /// 取值依据：细圈在 460px 工作分辨率下的原始掩码带宽约 20px（0.043×base），
    /// 而熔核本体是致密厚块（半宽 66px）。取 0.045×base = 21px 恰好能删掉 20px 的环带
    /// 而保留熔核。
    ///
    /// **默认 0（关闭），未启用**——它是一个已验证有效但会误伤的修法，先留着不动：
    ///   · 有效：在 20MP 现场数据上，SN_...0034 的 24 帧从 22 帧合格提升到 **24 帧全合格**
    ///     （07/22/23 三帧的并块被拆开，半径回到家族值 0.144×短边）；
    ///   · 误伤：核尺寸足够删掉 20px 环带时，**掩码稀疏的点位**会把熔核本体一起删掉。
    ///     实测 tests/tp 的 22.png（490×508）因此从合格变成"支撑弧段仅 35%"的测量失败，
    ///     合成图夹具（base 1024）出现 10 处失配。
    /// 要启用它，得先让"薄结构删除"自适应于掩码密度（例如只在掩码是致密厚块时才做），
    /// 或先把合成夹具改成尺度相对。在那之前，宁可留着每 SN 约 1~2 帧的伪漏焊，
    /// 也不要让旧相机样本变成测量失败。
    ///
    /// **2026-09-16 落地为「激进路径 + 核宽阶梯」**：主路径保持本项为 0（不做薄结构删除，
    /// 行为与之前一致）；只有当主路径找不到焊环、**或找到的半径落在实测族值带之外**时，
    /// 算法才按 <see cref="FallbackPreOpenKernelRatios"/> 的核宽阶梯重试，并**只采纳第一个
    /// 半径落回族值带的结果**。两处变化解决了本文档上面记录的那组矛盾：
    ///   · 触发条件从"完全找不到"扩到"半径不在族值带内"——因为细圈与熔核有间隔时，
    ///     细圈自成一环、内部被填洞成实心盘，会**按填洞面积压过真熔核**，主路径"看似成功"
    ///     却给出半径偏大 35% 以上的伪候选，旧条件永远命中不到它；
    ///   · "只采纳落回族值带的结果"让误伤不再成立——掩码稀疏的点位半径本来就在族值带内，
    ///     根本不会走到这条路上（它们的伪漏焊由主路径直接检出）。
    /// </summary>
    public double PreOpenKernelRatio { get; set; }

    /// <summary>
    /// 激进路径的薄结构删除核宽**阶梯**（× base），按顺序尝试，**采纳第一个半径落回族值带的结果**。
    ///
    /// 为什么需要阶梯：单次 0.045 对约 20px 厚的细圈是**临界值**——实测 Img000（OK_255）上它只删掉
    /// 一部分细圈，残留再被闭运算桥接回去，得到 0.173×短边（真值族值 0.145），圆心仍偏 116.9px。
    /// 逐级加大核宽能把这个残留彻底清掉；而"只采纳落回族值带的结果"这条守住了安全性：
    /// 核宽过大把熔核一起删掉时，结果要么找不到、要么半径不在带内，不会被采纳。
    ///
    /// 取值依据：细圈在 460px 工作分辨率下约 20px 厚（0.043×base），故第一级取 0.045 恰好临界；
    /// 目标熔核半宽约 66px（0.144×base），核宽远小于它，因此 0.075 一级仍不会吃掉熔核。
    /// 每一级只有在**半径落回族值带**时才会被采纳，所以阶梯的加长不会引入新的误判。
    /// </summary>
    public double[] FallbackPreOpenKernelRatios { get; set; } = { 0.045, 0.060, 0.075 };

    /// <summary>开运算核边长（× base），去掉孤立噪点。</summary>
    public double OpenKernelRatio { get; set; } = 0.030;

    /// <summary>候选焊环连通域的最小面积（× base²）。</summary>
    public double MinWeldBlobRatio { get; set; } = 0.002;

    /// <summary>圆度下限：距离变换峰值半径 / 等效半径。实心圆≈1，细长划痕/条带远小于 1。
    /// 用来把焊环与车削纹、划痕、台面亮带区分开。</summary>
    public double MinWeldRoundness { get; set; } = 0.55;

    /// <summary>圆度上限（>1 说明形状比等效圆更"厚实"，通常是粘连团块）。</summary>
    public double MaxWeldRoundness { get; set; } = 1.20;

    /// <summary>
    /// 焊环边界对拟合圆的最小支持角比例（0~1）：72 个角向扇区中，落有内点
    /// （径向距离在中位半径 ±10% 内）的扇区占比低于本值即判为**测量失败**。
    ///
    /// 拦的是"这个形状根本不是环"——划痕弧、台面亮带与熔核粘连成的异形块、碎裂的连通域，
    /// 以及**被环形光源反射细圈污染而残缺的边界**。这类形状拟合出来的圆心/半径没有物理意义，
    /// 报"合格/不合格"都是错的，只能交人工复核。
    ///
    /// **2026-09-17 由 0.50 提到 0.85（本轮修复的核心，只此一改动就解决了红圈偏离）**。
    /// 这道闸门本来就在 <see cref="Vision.WeldRingLocator"/> 末尾，是**唯一**对"圆心可信度"
    /// 有约束力的量；原值 0.50 形同虚设。48 帧（0054/0070 两个 SN）实测三个族群：
    ///   · 主路径采纳的 **40 帧良品**：0.93~1.00（真焊环的边界必须是整圈）；
    ///   · 厂商判 NG 的 12 帧现场图：**1.00**（"熔核整体明显变大"是厂商的 NG 形态）；
    ///   · "细圈与熔核并块"的污染帧 8 帧：0.51~0.94，其中圆心偏差最大的 4 帧
    ///     （66/82/94/103 原始像素 = 1.55/1.94/2.21/2.43mm）只有 **0.64/0.68/0.78/0.81**。
    /// 取 0.85 恰好落在这两个族群之间：拦掉全部 4 帧最坏的，而良品 40 帧与厂商 NG 一个不误伤。
    /// （为什么不是 0.90：0.90 会把半径正确、支撑 0.89、圆心只偏 9px 的帧也判成测量失败。）
    ///
    /// **为什么不用半径族值带来做这件事**（试过，被数据否定）：厂商 NG 的大熔核实测半径比
    /// 0.196~0.199，与"反射细圈被填洞成实心盘"的伪候选（0.193~0.200）在半径、圆度、
    /// 面积密度上完全重叠——**半径分不开"真·大熔核"与"伪候选"**，用它否决会一并废掉
    /// 厂商那一类缺陷（实测把带收紧到 0.135~0.152 后 `NgSamples_AreNotJudgedOk` 报 12/12 失败）。
    /// 能分开的是本项：污染帧的边界只有半圈，而真熔核（无论大小）的边界是一整圈。
    ///
    /// 历史标定记录（旧值 0.50 的依据）：28 张真机良品实测最低 0.60（15.png，孔洞分辨率已接近下限）。
    /// 那批图是**未经归一化的小图**（182~508px）；本项现在按归一化后的工作分辨率标定，
    /// 两者不可直接比较——这也是旧值偏松的原因之一。
    ///
    /// 已知代价（据实记录）：真正"未成环"的漏焊（残弧）也会落在本项之下，
    /// 于是被报成**测量失败**而不是**漏焊**。两种都不是 OK，但处置不同（复核 vs 报废）。
    /// 本轮没有可用于区分二者的真值样本（无已知的未成环漏焊件），故不改判定口径。
    ///
    /// **本项是随成像条件标定的配方参数，不是普适常数**（2026-09-17 实测结论）：
    /// 同一台算法在三套语料上的"正常帧"支撑弧段分别落在不同区间——
    ///   · 现场 20MP 图（5472×3648 归一化到 460）：良品 0.93~1.00；
    ///   · tests/tp 旧相机小图（182~508px）：28 张里有 6 张低于 0.82；
    ///   · 合成夹具（`WeldSceneRenderer` 散点画熔核）：干净帧 0.93~1.00，对抗性光照/漏焊帧 &lt;0.82。
    /// 因此生产默认取现场标定值 **0.82**；其它成像条件的语料在自己的配置里声明各自的值并写明依据
    /// （见 `RealisticRobustnessTests` / `RealSampleTests` 的 `_config` 初始化）。
    /// 现场那套值的守卫测试是 FIXPLAN 的 T1.9（用 tests/pp 真实帧）。
    /// </summary>
    public double MinRingArcSupport { get; set; } = 0.82;

    /// <summary>
    /// **第四路径**（掩码边界不像整圈、但尺度可信的候选交边界精修去定性）上的
    /// 掩码支撑弧段门限。0 = 关闭该路径。默认 0.50。
    ///
    /// 为什么需要一条**比 <see cref="MinRingArcSupport"/>（0.82）更低**的门限：
    /// 0.82 是拿**主路径的实心掩码**标定的（良品 0.93~1.00、污染帧 0.51~0.94），
    /// 而激进薄结构删除之后剩下的掩码在鱼鳞斑之间是**断裂**的，"掩码轮廓落在中位半径 ±10%
    /// 的角向扇区占比"这个量对它就失去了区分力——它测的是"掩码连不连续"，不是"熔核成不成圈"。
    ///
    /// 实测（现场 `SN_...0004` 第 10 帧 / OK_471，用户 2026-09-19 报的那张）：
    ///   · 主路径零候选（熔核在**阈值阶段**就与工件外框连成同一个贴边连通域）；
    ///   · 核宽阶梯 0.045/0.060/0.075 三级给出的半径比 0.1688 / **0.1376** / 0.1277
    ///     （厂商 `.vdb` 真值 0.1317），其中 0.060 一级的圆心 (335.6,234.8) 与厂商
    ///     (335.0,233.8) 只差 **1.2px**——几何完全正确；
    ///   · 但这三级的支撑弧段只有 64% / 60% / 61%，全部够不着 0.82，于是整帧报"测不出来"。
    ///
    /// 取 0.50 而不是更低：0.50 是 <see cref="MinRingArcSupport"/> 的**历史值**，也是
    /// "这个形状至少有一半圆周支持同一个圆"的物理下限；再往下就等于完全不看边界形状，
    /// 让本路径只靠半径与精修两道闸门把关。本路径**必须**由
    /// <see cref="Vision.WeldRingLocator.RefineBoundary"/> 转正——精修的支撑弧段是在 |∇I| 上量的，
    /// 与掩码是否连续无关，过不了 <see cref="MinRingArcSupport"/> 就退回"测不出来"。
    /// 因此本项只会把"测不出来"变成"测出来且边界成圈"，**不会**放宽任何判定。
    /// </summary>
    public double MinRingFallbackArcSupport { get; set; } = 0.50;

    /// <summary>
    /// 焊环半径下限（× base）。小于此值即"熔核未成形"，判**漏焊**（确定的缺陷，
    /// 不是测量失败）：伪漏焊点位实测只有 0.026~0.056×短边。
    ///
    /// 取 0.100 而不是更大：它同时是族值带的下界，要容纳其它视野/产品偏小的焊环
    /// （tests/tp 实测族值下限 0.130）。
    /// </summary>
    public double MinRingRadiusRatio { get; set; } = 0.100;

    /// <summary>
    /// 焊环半径**有效性**上限（× base）。超出判**测量失败**交人工复核（不是判炸焊）。
    ///
    /// **不要收到炸焊阈值以下**：<see cref="BlowoutRingRadiusRatio"/> = 0.26 的炸焊判据
    /// 正是"熔核半径明显偏大"，有效性上限若低于它，炸焊点位会先被当成测量失败而永远检不出来。
    /// 因此本项保持 0.32（高于炸焊阈值、也高于合成夹具的 0.275 渲染值），
    /// 而"剔除反射细圈伪候选"这件事交给更紧的 <see cref="RingRadiusFamilyMaxRatio"/>（0.18）
    /// 去触发重试，两件事互不干扰（2026-09-16 实测的分工）。
    /// </summary>
    public double MaxRingRadiusRatio { get; set; } = 0.320;

    /// <summary>
    /// 焊环半径**实测族值带**的上界（× base）——只用于两件事：**触发**激进路径重试、
    /// 以及**接受**重试候选（只采纳半径落在族值带内的重试结果）。下界用
    /// <see cref="MinRingRadiusRatio"/>。
    ///
    /// 它与 <see cref="MaxRingRadiusRatio"/> 必须分开，这一点曾被搞错过（2026-09-16 实测）：
    /// 起初把有效性上界从 0.32 直接收到 0.18，结果 62 个单元测试失败——因为**炸焊本来就靠
    /// "熔核明显偏大"来检出**（<see cref="BlowoutRingRadiusRatio"/> = 0.26，合成夹具按 0.275 渲染），
    /// 有效性上界低于炸焊阈值等于废掉炸焊检出能力。
    ///
    /// **本项刻意保持宽松（0.18），不承担"否决"职责**——这是 2026-09-17 一天里两次试错换来的结论：
    ///   · 先试过收紧到 0.135~0.152（现场 40 帧良品实测 0.1428~0.1466，看着很干净）。
    ///     结果是**厂商判 NG 的那 12 帧全部被这条判成"测量失败"**——它们实测半径比 0.196~0.199、
    ///     边界支撑 100%，即"熔核整体明显变大"正是厂商判 NG 的形态。收紧的带把它们一刀切掉，
    ///     等于废掉这一类缺陷的检出（`NgSamples_AreNotJudgedOk` 立刻报 12/12 失败）。
    ///   · 更根本的是：**伪候选与真·大熔核落在同一个半径区间**。反射细圈被填洞成实心盘的伪候选
    ///     实测 0.193~0.200，而厂商 NG 的大熔核实测 0.196~0.199——两者的"半径 + 填洞后圆度 +
    ///     面积密度"全都一样，**半径根本无法把这两件事分开**。所以本项不能用来否决。
    ///
    /// 真正的可信度判据是**边界支撑弧段**（<see cref="MinRingArcSupport"/>）：
    /// 实测 40 帧良品 0.93~1.00、厂商 NG 大熔核 1.00，而"细圈与熔核并块"的污染帧只有 0.51~0.94
    /// （4 帧最坏的 0.64/0.68/0.78/0.81）。本项与支撑弧段的分工因此固定为：
    /// **本项只决定"要不要再试一次"，支撑弧段决定"这个结果能不能信"。**
    /// </summary>
    public double RingRadiusFamilyMaxRatio { get; set; } = 0.180;

    /// <summary>
    /// 炸焊判据：熔核半径 / base 超过此值即判炸焊。正常焊点实测 0.1655±0.0120，
    /// 最大 0.208（该样本圆度 0.84 偏低，疑似飞溅粘连导致的过拟合，实际分布上限约 0.177）。
    ///
    /// 说明：本项目无真实炸焊样本，该阈值只能由良品分布外推得到——比良品最大值高 1.25 倍。
    /// 若实际炸焊仅使熔核增大 1.2 倍以内，本判据无法与良品区分，需用现场 NG 样本重新标定。
    /// 实践中炸焊几乎必然同时抛出大量飞溅，会由 Spatter 判据独立捕获，因此本判据不是唯一防线。
    /// </summary>
    public double BlowoutRingRadiusRatio { get; set; } = 0.260;

