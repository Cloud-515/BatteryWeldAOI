    /// </summary>
    public double PinRadiusFamilyRatio { get; set; } = 0.047;

    /// <summary>
    /// 径向搜索内边界（× **灰圆族值半径**，见 <see cref="PinRadiusFamilyRatio"/>）。
    ///
    /// **不要调大。** 从灰圆心朝背离孔洞的方向看，盘沿最近处在 q − D（q = 灰圆半径，D = 偏移量）。
    /// 搜索窗必须从盘内开始，即 rStart &lt; q − D，否则那些射线整条都落在熔核纹理上，
    /// "第一次上升沿"抓到的是鱼鳞斑而不是盘沿——拟合会收敛到一个**自洽但完全错误**的圆，
    /// 结果是焊偏 0.8mm 的点位被判合格（实测）。
    ///
    /// 历史：原为 0.05×焊环半径（≈9.3px）时在 D/q &gt; 0.55 就踩线；改为 0.02×焊环半径（≈3.7px）
    /// 后可靠区间扩到 D/q ≲ 0.79。本轮把基准从焊环半径换成灰圆族值半径（21.8px），
    /// 取 0.09 得到 ≈2.0px，与改动前的触底值一致；再往下无收益，反而在 D/q≈0.85 处变差
    /// （窗口太贴中心时起始"最平坦点"会被中心像素主导）。
    ///
    /// 残留极限：D/q → 1 时 q − D → 0，任何固定比例都保不住，此时拟合仍可能给出错误结果。
    /// 真机灰圆半径 ≈ 1.0mm，故可测上限约 0.8mm，见 <see cref="OffsetToleranceMm"/>。
    /// </summary>
    public double PinSearchInnerRatioOfFamily { get; set; } = 0.09;

    /// <summary>径向搜索外边界（× **灰圆族值半径**）。
