    /// <summary>
    /// **以熔核自身圆心为锚的焊环圆精修**——本组参数修的是"红圈框选偏移"：界面上那个红色焊环圈
    /// 与真实熔核不重合、且**同一个工件在不同帧里偏的方向还不一样**。
    ///
    /// ## 现象与实测证据（2025-09-11 现场 24 帧，逐帧与厂商 `.vdb` 及独立纹理边界拟合对照）
    ///
    /// 旧口径（连通域轮廓 + 中位半径拟合）测出的"焊环-孔洞"偏移在同一个工件上从 0.11mm
    /// 一路变到 3.66mm，而且**偏移方向随成像高光方向旋转**：偏移方向与"镜面饱和区质心方向"
    /// 夹角在 155°~180°（即偏移背向高光）。**这一条的现象描述仍然成立**——掩码在镜面冲白
    /// 的一侧确实缺失，整体圆拟合确实被推向背光侧。
    ///
    /// ## 2026-09-18 第二次修正：射线原点从"孔心"改为"熔核自身圆心"
    ///
    /// 上一版（`RefineWithPole`）用**孔心**当射线原点，并把搜索带锚在
    /// <c>1.15×族值中位</c>。这个做法把"熔核与极柱同心"当成了前提，而**"焊偏"本身正是要检验
    /// 这个前提**。实测后果（SN_CCSAGZZG01A2536925090900067025080700034，24 帧）：
    ///
    /// | 口径 | 与厂商圆心偏差 中位 / 最大 | 与独立纹理边界拟合 中位 |
    /// |---|---|---|
    /// | 孔锚精修（旧） | 131px / 152px | 78px |
    /// | 只用 Detect、不精修 | 11px / 29px | 12px |
    /// | **本版：自锚精修** | **9px / 32px** | **8px** |
    ///
    /// 机理（两条，都可复现）：
    ///   · **搜索带太窄**：带是以孔心为原点的 `[0.85, 1.15]×族值中位`；真熔核一旦偏心 d，
    ///     它到孔心的边界距离就摊成 `[R−d, R+d]`（实测 d 最大 160px = 半径的 33%），
    ///     绝大多数射线根本够不到真边界，只能在自己的带里挑一个噪声极值；
    ///   · **内点门限随之失效**：内点容差是 `max(3%×R, 2.0 工作像素)`，而工作分辨率下
    ///     2.0px = 16 原始像素，与带回的**半宽**（4%×474 = 19px）同量级——于是"随便挑的噪声"
    ///     也会被判成内点，支撑弧段实测恒在 0.84~0.99，那道门形同虚设。
    ///   结果：拟合退化成一个**几乎与孔心同心**的圆（实测 ex/ey 只有 ±12 原始像素），
    ///   把"焊偏"这个量直接抹平到接近零；而同一个圆在跨帧统计上"很稳定"——
    ///   这正是旧版测试把它读成"修好了"的原因（稳定性指标奖励了"把测量值压成常数"）。
    ///
    /// ## 精修做法（与孔心无关）
    ///
    ///  1. 以 <see cref="Vision.WeldRingLocator.Detect"/> 给出的**熔核圆心**为射线原点，
    ///     对种子周围的小 ROI 做 <see cref="WeldRingRefineUpsample"/> 倍上采样；
    ///  2. 逐射线量 |∇I|（对明暗极性免疫），用**中位数**聚合成径向剖面 g(r)；
    ///  3. 取 g(r) 里**从内向外第一段显著平台的外端**作为 <c>ρ</c>
    ///     （判据 g(r) &gt; <see cref="WeldRingRefineEdgeFraction"/> × 平台高度）；
    ///  4. 在 <c>ρ×(1−<see cref="WeldRingRefineBandInnerRatio"/>) ~ ρ×(1+<see cref="WeldRingRefineBandOuterRatio"/>)</c>
    ///     窄带内逐射线取**最后一段显著样本的外端**作为边界半径 b(θ)；
    ///  5. 对 b(θ) 做一阶谐波稳健拟合 b(θ) ≈ R + ex·cosθ + ey·sinθ，
    ///     **圆心 += (ex, ey)**，然后回到第 2 步迭代至收敛（&lt;<see cref="WeldRingRefineConvergePx"/>）。
    ///
    /// 迭代是关键：一阶谐波的 ex/ey 就是"当前圆心离真实圆心还有多远"，所以每轮都把原点搬正一点，
    /// ρ 与窄带也随之跟着真边界走。
    ///
    /// ## 实测（24 帧，同一 SN，原型与 C# 实现逐帧数值一致）
    ///
    /// | 口径 | 与厂商圆心 中位/p90/max | 半径 − 厂商半径 中位 |
    /// |---|---|---|
    /// | 不精修（掩码外缘） | 11.2 / 22.0 / 28.8px | +45px |
    /// | 孔锚精修（旧） | 131 / 150 / 152px | −25px |
    /// | 自锚 + 带内 argmax（中间版） | 10.8 / 16.3 / 31.7px | −8.0px |
    /// | **自锚 + 第一段平台（本版）** | **2.9 / 8.6 / 26.8px** | **+3.8px** |
    ///
    /// 对"细圈被填洞成实心盘"的帧（种子半径 654.7，真值约 485）本版给出 484.8；
    /// 对用户手绘真值的那一帧，圆心差由中间版的 33.9px 收到 **8.7px**（半径差 +31 → +13px）。
    ///
    /// ## 何时不精修
    ///
    /// 看不到边（纯平场）、边界不成圈（支撑弧段低于
    /// <see cref="WeldRingRefineMinArcSupport"/>）、或半径相对种子的修正量超过
    /// <see cref="WeldRingRefineMaxRadiusCorrection"/> 时返回 null，保持 <see cref="Vision.WeldRingLocator.Detect"/>
    /// 的原结果。**只改善、不引入新的测量失败**（调用方另有半径有效性区间把关）。
    /// </summary>

    /// <summary>
    /// 精修的**径向剖面范围**（× 当前圆心处的半径）：剖面在
    /// <c>[R×本值, R×<see cref="WeldRingRefineProfileOuterRatio"/>]</c> 上采样。
    ///
    /// 为什么必须是"当前圆心"而不是孔心：见 <see cref="WeldRingRefineEdgeFraction"/> 的因果链。
    /// 下界取 0.35 而不是贴着种子：种子可能是"细圈被填洞成实心盘"的伪连通域（实测半径 654.7
    /// 而真熔核只有 485），真熔核边界落在种子半径的 0.74 倍处——下界必须够得着它。
    /// 上界取 1.25：够得着外侧那条 1.23×半径的凹陷细暗圈，好让"哪一圈才是熔核"由
    /// <see cref="WeldRingRefineEdgeFraction"/> 的"第一段平台"判据去决定，而不是靠搜索带硬挡。
    /// </summary>
    public double WeldRingRefineProfileInnerRatio { get; set; } = 0.35;

    /// <inheritdoc cref="WeldRingRefineProfileInnerRatio"/>
    public double WeldRingRefineProfileOuterRatio { get; set; } = 1.25;

    /// <summary>
    /// 精修在 ROI 上的**上采样倍数**。
    ///
    /// 需要它的原因：精修跑在 <see cref="MaxWorkingBase"/> 归一化后的工作分辨率上，
    /// 那里熔核半径只有约 60px，±10% 的窄带只有 6px——逐射线取"最后一段显著样本"的
