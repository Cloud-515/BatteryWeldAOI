    /// <summary>
    /// 卡尺兜底结果的**逐射线残差**上限（× 该次拟合的半径）。越界即判"孔位不可信"，
    /// 报**测量失败**交人工复核，而不是给出一个静默错误的偏移量。
    ///
    /// ## 为什么必须有这道判据
    ///
    /// `HoleLocator` 返回 null 时算法会**无条件**退到 `PinLocator.Locate`，而它的射线原点
    /// 是**焊环圆心**、搜索窗只有 `[PinSearchInnerRatioOfFamily, PinSearchOuterRatioOfFamily] ×
    /// 族值半径`。孔心一旦离焊环圆心较远（实测 Img000 为 1.32× 真孔半径），朝孔一侧的射线抓到
    /// 孔沿、背孔一侧抓到熔核内沿，正弦拟合把两者平均成一个**自洽但无意义**的圆。
    ///
    /// 实测（用户手绘标注反解出的真值，Img000 / 19-22-06 帧）：
    ///   · 卡尺给出 `圆心 (2641.9,1712.4) r=170.3`（原图像素），真值 `(2389,1792) r=143`；
    ///   · 圆心偏 **6.21mm**、半径 1.19 倍（相对用户卡尺实测的 5mm 孔半径 106.6px 则为 1.60 倍）；
    ///   · 偏移量报 **1.761mm 而真值 ≈4.45mm（偏低 2.5 倍），界面仍判 OK**
    ///     —— 属于"该判 NG 却判合格"的方向，必须拦住。
    ///
    /// ## 取值依据（40 SN / 933 帧实测，其中卡尺兜底 72 帧）
    ///
    /// 实测（残差 ÷ 拟合半径）：卡尺帧 中位 **0.166**、p75 0.220、p90 0.261、p95 0.384、max 0.572；
    /// 用户报的 Img000 那一帧为 **0.172**——**恰好落在中位上**。
    /// 也就是说这条判据**不能靠"值大"来指认坏帧**：卡尺路径在本产品上的残差整体就大，
    /// 因为它的模型前提（`D < 0.8 × 孔半径`）在本产品上普遍不成立（实测真值 D/q ≈ 1.32）。
    /// 这正是"这条兜底路径对这个产品本来就不该被信任"的量化证据。
    ///
    /// 取 **0.10**（落在卡尺帧的 p25~p50 之间）的含义是明确的口径选择：**只有拟合明显紧于
    /// 它自身常态时才接受卡尺结果，否则报"孔位不可信"交人工复核**——与仓库既有的
    /// "宁可不测，不可伪造"一致。实测 40 SN / 933 帧的代价与收益：
    ///   · 改动前：72 帧走卡尺（含 4 帧报"孔洞半径异常"，其中 3 帧其实可测）；
    ///   · 分层判据改造（见 `Vision.HoleLocator`）后绝大多数这类帧由分层路径正常测出，
    ///     真正还需要卡尺的帧大幅减少；
    ///   · 剩下的卡尺帧里，本判据把"与孔沿不自洽"的（含用户报的 16-48-56 静默错帧）转为复核。
    /// </summary>
    public double CaliperMaxResidualRatio { get; set; } = 0.10;

