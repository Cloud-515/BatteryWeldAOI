    /// </summary>
    public double MaxPinRadiusRatio { get; set; } = 0.40;

    /// <summary>
    /// **孔位外径弧**路径输出的半径上限（× 焊环外半径）。只作用于
    /// <see cref="Vision.HoleLocator"/> 的 FitOuterArc 分支，卡尺与中间层两条路径仍用
    /// <see cref="MaxPinRadiusRatio"/>（0.35）。
    ///
