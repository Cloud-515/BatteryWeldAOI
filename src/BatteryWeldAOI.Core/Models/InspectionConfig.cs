    public double DualScaleThresholdK { get; set; } = 0.45;

    /// <summary>
    /// 孔洞半径上限（× 焊环半径）。
    ///
    /// **2026-09-18 由 0.35 提到 0.40——因为本闸门的分母换了口径，必须同步。**
    /// 环半径现在由 <see cref="Vision.WeldRingLocator.RefineBoundary"/> 按 |∇I| 量熔核外沿给出，
    /// 比旧的"纹理掩码连通域外缘"小约 8%（掩码外缘被闭运算核与填洞往外撑了 45px / 490px ≈ 9%，
    /// 见 <see cref="WeldRingRefineEdgeFraction"/> 的实测表）。本闸门是 **÷环半径** 的比例量，
    /// 分母变小 8% 就等于判据收紧 8%——实测 20 个 SN / 448 帧"定位干净"的帧里有 15 帧
    /// （3.3%）因此被误判为"孔洞半径异常"，而它们的环心与厂商只差 &lt;40px、支撑弧段 ≥0.82，
    /// 即**测量本身是好的，是判据口径没跟上**。
