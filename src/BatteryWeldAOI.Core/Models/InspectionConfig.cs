    /// **必须与原窗口等效**：改动前的窗口是 `0.55 × 焊环半径`，换算成灰圆族值半径的倍数就是
    /// `0.55 × (焊环半径/base) ÷ PinRadiusFamilyRatio`——tests/pp 的环径比 0.145 给出 1.70、
