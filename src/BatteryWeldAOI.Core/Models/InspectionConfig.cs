    /// </summary>
    public double WeldRingRefineEdgeFraction { get; set; } = 0.45;

    /// <summary>平台高度取显著样本（&gt;5% 剖面最大值）的哪一个分位。见 <see cref="WeldRingRefineEdgeFraction"/>。</summary>
    public double WeldRingRefinePlateauPercentile { get; set; } = 75;

