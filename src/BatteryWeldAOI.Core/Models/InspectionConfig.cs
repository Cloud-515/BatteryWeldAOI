    /// </summary>
    public double WeldRingRefineMinRunRatio { get; set; } = 0.06;

    /// <summary>
    /// 逐射线搜索带的**内边界**（ρ×(1−本值)）。ρ 已由"第一段平台"定住，所以带宽只需要
    /// 覆盖"圆心还不准"带来的径向展宽（±偏移量）；取 0.10 对应偏移量 ≲ 10%×半径。
    /// </summary>
    public double WeldRingRefineBandInnerRatio { get; set; } = 0.10;

    /// <summary>
    /// 逐射线搜索带的**外边界**（ρ×(1+本值)）。
    ///
    /// **比内边界小**（0.08 vs 0.10）是刻意的：熔核外侧紧邻"细密灰斑噪声带"，外边界每放宽 1%，
    /// 就有更多射线的"最后一段显著样本"落进那条带里。实测内 0.10 / 外 0.08 时 Img000 与用户
    /// 手绘真值的圆心差 8.7px；改成对称的 0.08 两侧（即内 0.08/外 0.08）或内 0.08/外 0.06 都会变差。
    ///
    /// **但它只是第一级**：ρ 由全周中位剖面给出，在"熔核有一大段被镜面冲白"的帧上会被系统性低估，
    /// 此时窄带会把真边界**硬截在带外端**（实测 `SN_...0007` 第 1 帧 ρ=450 而真值约 505，
    /// 红圈因此偏小 23px、圆心偏 19px）。这类帧由
    /// <see cref="WeldRingRefineBandOuterFallbacks"/> 的阶梯接住，判据见
    /// <see cref="WeldRingRefineMaxClippedRatio"/>。
    /// </summary>
    public double WeldRingRefineBandOuterRatio { get; set; } = 0.08;

    /// <summary>
    /// 外带宽的**加宽阶梯**（依次尝试，直到"截断比"达标；见
    /// <see cref="WeldRingRefineMaxClippedRatio"/>）。
    ///
    /// 每一级都要重跑整条精修（含圆心迭代），因为 ρ 低估不仅影响带的位置，也把圆心拉偏
    /// ——实测第 1 帧窄带给出圆心 (2693,1785)、宽带给出 (2677,1802)，两者差 19px。
    ///
    /// 取 { 0.20, 0.32 } 的依据（`SN_...0007` 24 帧实测）：0.20 一级已把该帧的截断比从 0.45
    /// 降到 0.07（圆心与厂商差由 19.1px 收到 4.1px）；0.32 只是保险。**上限不能再放宽**：
    /// 实测 0.40 会让"熔核外侧的灰斑带"整段进入搜索范围，把 4 帧做成完全不同的圆
    /// （偏差 55~153px）；而 0.30 在另外几帧上也会把半径拱到 594~600px。
    /// 之所以安全，是因为**只有截断比超限的帧才会往下走**，而这类帧的窄带结果本身已经不可用。
    /// </summary>
    public double[] WeldRingRefineBandOuterFallbacks { get; set; } = { 0.20, 0.32 };

    /// <summary>
    /// 是否启用**第三路径（先删贴边连通域）**兜底。默认开启。
    ///
    /// 只在前两条路径（主路径 + 核宽阶梯/双尺度）都没给出可用结果时启用；采纳条件还要求
    /// 半径 ≤ <see cref="MaxRingRadiusRatio"/>。修的是"熔核被闭运算桥接进工件外框、
    /// 于是被'贴边=背景'规则连熔核一起扔掉"这一类（现场 Img010 型：画面里焊环清晰可见却报无焊点）。
    /// 完整实测记录见 <see cref="Vision.WeldRingLocator.Detect"/> 的 preCleanBorder 参数。
    /// </summary>
    public bool EnableRingBorderCleanupFallback { get; set; } = true;

    /// <summary>
    /// 精修时**两个起点的最大允许分歧**（× 半径）——**当前未被算法使用，只作诊断量**。
    ///
    /// 2026-09-19 试过把它作为"逐级放宽外带宽"的第二个触发条件（动机：黑环帧上窄带会把
    /// 第二起点（孔心）困在一个偏小、但支撑弧段假性偏高的圆上），**40 SN / 960 帧实测被否定**：
    /// 28 帧变好、**13 帧变差**（含当初靠第二起点救回的 `SN_...0003` OK_933/OK_936），
    /// 尾部指标净退化——与厂商圆心偏差 **max 49.2px → 63.5px**、半径比带外帧 **0 → 1**。
    /// 故不接入算法，仅保留此配置项与 `RingRefinement.ResidualScatter` 供后续诊断参考
    /// （完整实测见 FIXPLAN 第 8 节）。
    ///
    /// 实测分布（用于将来重新评估）：健康帧两个起点一致到 ≤0.2px（0.003×半径）；
    /// 黑环帧 3.4px / 7.0px（0.049 / 0.098×半径）；而被误伤的帧分歧本就 ≈0。
    /// **关键结论**：分歧小并不能证明结果正确（被误伤的帧分歧就是 0），
    /// 所以它不能单独用作"放宽"的触发条件。
    /// </summary>
    public double WeldRingRefineMaxStartDisagreement { get; set; } = 0.02;

    /// <summary>
    /// **边界粗糙度闸门**：第二起点（孔心）的边界径向粗糙度必须至少是主起点（熔核心）的
    /// 这么多倍，否则**不允许它接管**主起点的结果。0 = 关闭。默认 0.5（启用）。
    ///
    /// ## 它修的是什么（2026-09-20，FIXPLAN 第 9 节）
    ///
    /// 工件上直径 30mm 凹陷台阶的阴影边（"黑环"）**与孔同轴**，是一条**机加工锐边**：
    /// 它在 |∇I| 上比焊道纹理强一倍（实测中位剖面峰值 117.5 vs 主起点的 70.6），
    /// 于是以**孔心**为射线原点的精修会被它吸走，收敛到一个"自洽但偏小"的圆，
    /// 而其支撑弧段**假性偏高**（95.3% vs 主起点 82.4%）——仲裁规则（弧段更高者胜）于是选错。
    /// 实测 `SN_...0004` 第 0 帧（`22-59-49 478 / OK_441`）：主起点 (332.4,224.5) r=65.9
    /// （离厂商圆 2.5 工作像素，**对的**），第二起点 (326.3,221.0) r=60.5（离厂商 4.5），
    /// 最终报出 **35.8 原始像素**偏差。
    ///
    /// ## 判据的物理依据：焊道外沿粗糙、机加工边光滑
    ///
    /// 激光焊熔核外沿是**鱼鳞状凝固组织**，其径向粗糙度是焊道本身的物理属性；
    /// 机加工台阶阴影边是**锐边**。因此"锁定到真焊道"与"锁定到机加工边"在
    /// <see cref="RingRefinement.ResidualScatter"/> 上分得开：
    ///
    /// | 帧 | 主起点残差 | 第二起点残差 | 比值 | 正确解 |
    /// |---|---|---|---|---|
    /// | `OK_441`（要修的黑环帧） | 0.0302 | **0.0129** | **0.43** | 主起点 |
    /// | `OK_936`（4.9 节靠第二起点救回） | 0.0188 | **0.0300** | **1.60** | 第二起点 |
    /// | `OK_444`（黑环帧，已合格 12.9px） | 0.0328 | 0.0244 | 0.74 | 主起点 |
    /// | `OK_933`（第二起点距主起点 1.8px，被跳过） | — | — | — | 主起点 |
    ///
    /// 取 0.5 落在 0.43 与 1.60 之间（分离度 3.7 倍）。**必须用比值而不是绝对阈值**——
    /// 残差随上采样倍数、内点容差、工作分辨率一起变，绝对量不可移植。
    ///
    /// ## 实测（40 SN / 960 帧 A/B）
    ///
    /// **3 帧变好、1 帧在容差内小幅变差**，判定分布与**尾部指标一字未变**
    /// （max 49.2px、p90 6.8px、半径比带外 0 帧）。
    /// 与第 8 节那两种被否定的修法（max 49.2 → 63.5px）的关键区别就在这里。
    ///
    /// ## 与 ρ 一致性闸门的关系（据实记录）
    ///
    /// 第 10 节还试过 <see cref="WeldRingRefineMinRhoRatio"/>（"两个起点量到的是不是同一条边界"），
    /// 它在 960 帧上**比本项更强**（9 帧变好 1 帧变差、p95 17.1→14.7），
    /// 但它的那一帧变差**有独立物理证据说明它判错了**（`OK_933` 的熔核半径必须 ≈489px，
    /// 而它保留了 527px 的主起点），故该闸门默认关闭。**本项保留为生产默认。**
    /// </summary>
    public double WeldRingRefineMinRoughnessRatio { get; set; } = 0.5;

    /// <summary>
    /// **ρ 一致性闸门**：第二起点（孔心）量到的 ρ（"熔核纹理到哪儿结束"的半径）必须至少是
    /// 主起点（熔核心）的这么多倍，否则**不允许它接管**。0 = 关闭该闸门。默认 0.98。
    ///
    /// ## 物理依据（这是本项相对"边界粗糙度"那个代理量的优势）
    ///
    /// ρ 是精修在**全周中位 |∇I| 剖面**上取"第一段显著平台外端"得到的半径，含义是
    /// "这个圆心看出去，熔核纹理到哪儿结束"。两个起点若量到的是**同一条物理边界**，
    /// 它们的 ρ 必然接近；ρ 出现可见差异，说明其中一方锁到了**别的结构**
    /// （机加工阴影边、反射细圈、散斑带）。所以本项量的不是"哪个圆更像圆"，
    /// 而是"两个圆心看到的是不是同一个东西"——这比拟合质量类判据直接得多。
    ///
    /// ## 实测（2026-09-20 离线判别研究，40 SN / 945 个决策帧，FIXPLAN 第 10 节）
    ///
    /// 判据是拿**厂商 `.vdb` 圆当标签**做的：每帧把两个起点各自单独跑一遍，
    /// 比谁离厂商圆更近，再回头看哪个量能预测"该选谁"。结果：
    ///
    /// · **弧段差、归一化残差、绝对粗糙度、截断比、effArc 全部完全重叠**——
    ///   两组的中位数相同、p10/p90 也几乎相同（例如弧段差两组 p10 分别是 −0.0125 / −0.0014，
    ///   中位都是 0.0000）。**这些量都预测不了"该选谁"**，这是本轮最重要的负面结论。
    /// · **只有 ρ 比值与半径比值分得开**，且 ρ 更干净：该选次时 ρ比值 p10 = **0.9998**，
    ///   该选主时 p10 = **0.9810**。
    ///
    /// 阈值处的两组分布（决策子集 714 帧，该选主 303 / 该选次 245）：
    ///
    /// | 阈值 | 该选主被拦（=拦对） | 该选次被拦（=误伤） |
    /// |---|---|---|
    /// | 0.995 | 45/303 (14.9%) | 5/245 (2.0%) |
    /// | 0.990 | 40/303 (13.2%) | 2/245 (0.8%) |
    /// | **0.980** | **30/303 (9.9%)** | **1/245 (0.4%)** |
    /// | 0.970 | 21/303 (6.9%) | 1/245 (0.4%) |
    /// | 0.950 | 6/303 (2.0%) | 1/245 (0.4%) |
    ///
    /// 取 **0.98**：误伤已降到最低（1 帧）而拦对仍接近最大，分离度 **25 倍**。
    ///
    /// ## 阈值的硬约束（由已知帧钉死，不是拍的）
    ///
    /// 阈值必须落在 **(0.9527, 0.9851)** 之间：
    /// · 上界来自 `SN_...0003` 的 `16-48-50 168`（FIXPLAN 4.9 靠第二起点救回的帧，
    ///   第二起点 3.3px、主起点 28.2px）——它的 ρ 比值是 **0.9851**，阈值再高就会破坏它；
    /// · 下界来自 `SN_...0003` 的 `16-49-04 649`（**用户 2026-09-20 报的那帧**，
    ///   主起点 5.9px、第二起点 26.4px）——它的 ρ 比值是 **0.9527**，阈值再低就拦不住它。
    ///
    /// 七个已知帧在本阈值下**全部判对**（含第 9 轮粗糙度闸门判错的那一帧）：
    ///
    /// | 帧 | ρ比值 | 本闸门 | 正确解 |
    /// |---|---|---|---|
    /// | `0302/16-48-50 168` | 0.9851 | 放行 | 第二起点 |
    /// | `0402/22-59-50 992` | 0.9810 | 放行 | 主起点（本就不接管） |
    /// | `3602/07-28-34 510` | 0.9595 | 拦下 | 主起点 |
    /// | `0302/16-49-04 649`（用户报的帧） | 0.9527 | 拦下 | 主起点 |
    /// | `0402/22-59-49 478` | 0.9458 | 拦下 | 主起点 |
    /// | `0502/21-39-00 506` | 0.9391 | 拦下 | 主起点 |
    /// | `1802/14-58-52 472` | 1.0614 | **放行** | 第二起点（第 9 轮在此判错） |
    ///
    /// ## ⚠️ **默认关闭（0）——本项实测被否定，不要直接启用**
    ///
    /// 960 帧 A/B 上它比第 9 轮的粗糙度闸门**更强**：**9 帧变好、1 帧变差**，
    /// p95 17.1 → **14.7px**、>30px 由 21 → **17 帧**、max 49.2px 不变。
    /// 但它唯一变差的那一帧**有独立的物理证据说明它判错了**：
    ///
    /// · `SN_...0003` 的 `16-48-48 544 / OK_933`：本闸门拦下第二起点后保留主起点，
    ///   其半径是 **527 原图像素**；而该帧熔核半径**必须** ≈489
    ///   （同 SN 其余 20 帧实测 483~493，且厂商 `.vdb` 给 489.1）。
    ///   即闸门让结果变成了**物理上不可能**的值。
    ///
    /// **根因（本项无法克服的局限）**：ρ 比值只能测出"两个起点不一致"，
    /// **测不出"是谁错了"**。该帧错的是**主起点**（种子圆心被细圈/外侧碎斑带撑歪 39~45px，
    /// 见 FIXPLAN 4.9），而闸门却去惩罚正确的第二起点。
    ///
    /// 五个已知帧的 ρ 比值排序说明了为什么"换个阈值"救不了：
    /// `0.9370 OK_933（该放行）` &lt; `0.9458 OK_441（该拦下）` &lt; `0.9527 OK_963（该拦下）`
    /// ——"该放行"的那个夹在两个"该拦下"之间，**阈值区间为空**。
    ///
    /// **要启用它，先得有一个能判断"谁在离群"的独立基准**，例如按产品标定的熔核半径带
    /// （本仓库目前只有很宽的族值带 [0.100, 0.180]，分辨不出 0.1445 与 0.1341）。
    /// 那属于"配方/标定"层的工作，见 FIXPLAN 第 10.6 节。
    ///
    /// ## 它不能解决什么（据实记录）
    ///
    /// 离线研究给出**上界**：即使有一个完美仲裁器（每帧都选离厂商更近的那个），
    /// 决策子集上的 p95 只能到 13.4px、**max 仍是 49.2px**。也就是说
    /// **最差的那几帧在两个起点上都不好**，尾部由种子/几何本身决定，
    /// 换任何仲裁规则都压不下去。
    /// </summary>
    public double WeldRingRefineMinRhoRatio { get; set; }

    /// <summary>
    /// **第五路径（多起点重试）的网格步长**（× 候选圆半径），0 = 关闭该路径。默认 0.13。
    ///
    /// ## 它修的是什么（2026-09-20，FIXPLAN 第 11 节）
    ///
    /// 有一类帧：**熔核外沿在 |∇I| 上完全可测，但由纹理掩码算出的候选圆心偏了**，
    /// 而精修从偏掉的圆心出发会落进另一个"自洽但错误"的盆地。实测
    /// `SN_...0502` 的 `21-39-16 665 / OK_597`：
    ///
    /// · 用厂商 `.vdb` 的圆当种子跑我们的精修 → **支撑弧段 99.2%**、离厂商 18px；
    /// · 用掩码质心当种子 → 落进 r=535、弧段 70% 的错误盆地；
    /// · 两个种子只差 **2.5 工作像素**——这是**分叉**，没有哪个"更好的估计器"能可靠地
    ///   落在正确一侧，**必须搜索**。
    ///
    /// ## 盆地实测（这是网格参数的唯一依据，两帧独立标定）
    ///
    /// 步长取 **0.13×半径**（工作分辨率下约 8px），偏移取 {0, ±1, ±2}×步长（5×5 = 25 个种子）：
    ///
    /// | 帧 | 过弧段门限的格子 | 弧段最高者 | 距厂商圆 |
    /// |---|---|---|---|
    /// | `21-39-16 665`（本帧原报"异常"） | 10/25 | r=486 弧段 **99.2%** | **18.3px** |
    /// | `17-01-23 304`（本帧原报"异常"） | 4/25 | r=483 弧段 **95.4%** | **3.7px** |
    ///
    /// 两帧**所有过门限的格子彼此一致**（距厂商 中位 18.5/max 19.0 与 3.9/4.2），
    /// 说明"取弧段最高者"不是在噪声里挑。而**半径分不开两个盆地**
    /// （正确 486~489 vs 错误 450~539，重叠），所以仲裁只能用弧段。
    ///
    /// ## 为什么不会误伤（三条，缺一不可）
    ///
    /// 1. **触发面**：只在**前四条路径全都给不出可信结果**时启用——也就是"本来就会报
    ///    测量失败"的帧。实测 40 SN / 960 帧里只有 2 帧走到这里。
    /// 2. **采纳面**：候选必须过 <see cref="MinRingArcSupport"/>（0.82）**且**半径落在
    ///    有效性区间内才被考虑。错误盆地的弧段只有 68~74%，过不了这道门。
    /// 3. **质量指标已验证**：修好圆心之后，漏焊判据仍要过——实测两帧的环弧覆盖率
    ///    0.917 / 1.000（下限 0.75）、熔核填充率 0.652 / 0.850（下限 0.45），都通过。
    ///    否则修好圆心只会把"异常"变成**伪造的漏焊 NG**，那是更糟的结果。
    ///
    /// 代价：这类帧单点耗时增加约 25 次精修（每次约 0.2s，合计约 5s）。因为只发生在
    /// 本来就要报错的帧上，对节拍无实质影响。
    /// </summary>
    public double MultiSeedRetryStepRatio { get; set; } = 0.13;

    /// <summary>
    /// 第五路径的**网格环数**：偏移取 {0, ±1, …, ±本值} × <see cref="MultiSeedRetryStepRatio"/>，
    /// 共 (2×本值+1)² 个种子。默认 2（5×5 = 25 个）。0 = 只试中心那一个。
    /// 取 2 的依据见 <see cref="MultiSeedRetryStepRatio"/> 的两帧盆地图。
    /// </summary>
    public int MultiSeedRetryRings { get; set; } = 2;

    /// <summary>
    /// "截断比"上限：有效射线中边界落在**外带边界以内 2 个上采样采样点**的比例。
    ///
    /// 它的含义是"这条带够不够宽"——射线密度在带外端堆积说明真正想要的边界在带外，
    /// 即 ρ 被低估了。此时窄带给出的不只是半径偏小，**支撑弧段还是假的**：
    /// 被截断的射线全部落在同一个半径上，内点判定当然全部通过（实测该帧支撑弧段 0.86，
    /// 而放宽重跑后是 0.74——后者才是诚实的读数）。
    ///
    /// 取 0.15 的依据（`SN_...0007` 24 帧实测）：健康帧 0.00~0.09（最大是第 0 帧的 0.09，
    /// 它的结果与厂商只差 2.3px，属正常波动）；问题帧 0.45。两者之间留了 1.7 倍余量。
    /// </summary>
    public double WeldRingRefineMaxClippedRatio { get; set; } = 0.15;

    /// <summary>
    /// 单条射线内"显著样本"的判定（× 该射线在带内的峰值）。从外向内取**第一个**超过本值的样本
    /// 作为该射线的边界——即"这条射线上纹理最后出现在哪里"，而不是"梯度最大在哪里"。
    ///
    /// 这个区别是关键：梯度最大处落在过渡带**内部**，而熔核外沿是过渡带的**外端**；
    /// 取最大处会给出一条系统偏大的圆。取 0.35。
    /// </summary>
    public double WeldRingRefinePerRayFraction { get; set; } = 0.35;

    /// <summary>
    /// 判定"这条射线没有可量的边"（落在镜面冲白区）的门限：射线在带内的峰值低于
    /// <c>本值 × τ</c> 即弃用该射线。这类射线在真机上可占四成，必须显式剔除——
    /// 若把它们按"纹理在带内起点就结束"计入，会把拟合圆心拉向冲白侧。
    /// </summary>
    public double WeldRingRefineDeadRayFraction { get; set; } = 0.25;

    /// <summary>
    /// 精修结果的**边界支撑弧段**下限（0~1，内点占比）。低于此值说明这条"边界"根本不成圈
    /// （视野里没有焊环、或真熔核被冲白到看不出一条连续的边），此时放弃精修、保持旧结果。
    ///
    /// 取 0.50：实测用户 SN 24 帧自锚精修的内点占比 0.86~0.99。
    /// **注意本门限只有在"内点容差远小于搜索带半宽"时才有区分力**——旧版孔锚精修
    /// 之所以门限失效，正是因为 2.0 工作像素的绝对下限与 19 原始像素的带半宽同量级
    /// （见 <see cref="WeldRingRefineEdgeFraction"/>）。
    /// </summary>
    public double WeldRingRefineMinArcSupport { get; set; } = 0.50;

    /// <summary>
    /// 精修迭代次数上限。一阶谐波的 (ex, ey) 就是"圆心还差多远"，实测 2~3 轮即收敛到
    /// &lt;0.4px（<see cref="WeldRingRefineConvergePx"/>）；上限只是防病态输入死循环。
    /// </summary>
    public int WeldRingRefineIterations { get; set; } = 5;

    /// <summary>精修迭代的收敛判据（工作像素）：本轮圆心位移小于本值即停止。</summary>
    public double WeldRingRefineConvergePx { get; set; } = 0.4;

    /// <summary>
    /// 精修结果允许的**半径修正量上限**（|R_精修 − R_种子| / R_种子）。
    ///
    /// 这是防"搬到另一个结构上"的安全阀。取 0.45：实测最大修正量 26%
    /// （细圈填洞帧 654.7 → 484.8），留约 1.7 倍余量。
    /// </summary>
    public double WeldRingRefineMaxRadiusCorrection { get; set; } = 0.45;

    /// <summary>
    /// 精修结果的**内点判定容差**（× 当前半径）。逐射线的边界点落在这个相对容差内才算内点。
    ///
    /// **取 0.06（旧版 0.03）**：本值必须与搜索带一起看——容差太小会把"边界本身的真实粗糙度"
    /// （熔核外沿是鱼鳞状的，不是理想圆）也判成外点，支撑弧段从而虚低；太大则失去区分力。
    /// 实测 24 帧：0.06 给出 0.86~0.99 的支撑弧段，与目视"这条边界确实是一整圈"一致。
    /// </summary>
    public double WeldRingRefineInlierTolerance { get; set; } = 0.06;

    /// <summary>径向剖面的射线数与逐射线采样条数（精修的角向分辨率）。取 720 与轮廓拟合的 72 档一致偏细。</summary>
    public int WeldRingRefineRays { get; set; } = 720;

    /// <summary>
    /// 熔核**内沿**搜索的起点（× **灰圆半径**，以焊环圆心为原点）——跳过极柱及其边缘带。
    ///
    /// 极柱边缘是亮→暗阶跃，局部标准差（纹理能量）同样很高，从极柱内部起搜会把极柱边缘
    /// 误当成熔核内沿。取 1.15 倍灰圆半径，正好跳过极柱边缘并落在其外的暗缝隙里。
    /// 实测（tests/pp）：熔核内沿半径中位约 0.31×焊环外半径，比极柱半径大约 25px——
    /// 两者确实是**两条不同的边**（这也印证了"极柱是独立零件、熔核内外沿同心于激光中心"）。
    ///
    /// **2026-09-17 已知退化（据实记录）**：本参数的物理含义以"灰圆半径可信"为前提，
    /// 而灰圆半径在孔位基准修正后从卡尺输出的 0.32×焊环半径回落到真实的 0.15×，
    /// 于是起点从 0.37×焊环半径降到 0.17×、落进了孔的内部，内沿取到率由 100% 降到 72%
    /// （取不到时按设计不输出环宽，界面显示"本次未取到熔核内沿"）。同时要说明旧值 100%
    /// 的取到率**有一部分是假象**：旧起点/焊环半径 = 0.339 而当时量到的内/外半径比中位 0.374，
    /// 两者几乎相同，即那个"内沿"主要来自起点本身。环宽是纯诊断量、不参与判定，
    /// 要修好需要给"第一次超阈值"加持续性判据（详见 <c>WeldInnerLocator</c> 内的记录），本轮未做。
    /// </summary>
    public double WeldInnerSearchStartRatio { get; set; } = 1.15;

    /// <summary>熔核内沿搜索的终点（× 焊环外半径）。留在外边界之内，避免把外沿本身当中沿。</summary>
    public double WeldInnerSearchOuterRatio { get; set; } = 0.95;

    /// <summary>
    /// 认定"内沿命中"所需的**持续超阈长度**（工作像素）。
    ///
    /// 2026-09-17 新增。此前取的是"沿射线的**第一次**超过能量阈值"，而极柱边缘是亮→暗阶跃、
    /// 局部标准差本来就高，搜索起点附近的第一个样本往往就已超阈——于是返回的"内沿半径"
    /// 恒等于搜索起点 `WeldInnerSearchStartRatio × 极柱半径`，环宽成了纯人工产物。
    /// 实测两帧严格吻合该恒等式：Img010 内半径 159.5 = 1.15×138.4；Img003 241.1 = 1.15×209.9。
    ///
    /// 取 6：鱼鳞斑内部的单点/窄带高能量与极柱边缘带都被它滤掉（它们都远窄于 6 个像素），
    /// 而真实的内沿是一条连续的粗糙起始边界，一次跨过去就不会退回来。
    /// 代价是内沿取到率下降——取不到时按设计显示「—（本次未取到熔核内沿）」而不是给一个假数；
    /// 环宽是纯诊断量、不参与判定，所以这个代价是划算的。
    /// </summary>
    public double WeldInnerMinRunPx { get; set; } = 6.0;

    /// <summary>
    /// 熔核内沿与外边界允许的**同心偏差**（× 焊环外半径）。超过则认为内沿不可信、不予输出
    /// （不判测量失败——环宽本轮是新增的诊断量，不参与判定）。
    ///
    /// 实测：良品内外圆心偏差中位 1.3px（外半径 526px 时约 0.0025×半径）；
    /// 而两个含反射细圈残留的帧偏差达 48.8px（约 0.07×半径）。取 0.05 把两者分开。
    /// </summary>
    public double WeldInnerMaxConcentricDeviationRatio { get; set; } = 0.05;

    // ---- 孔位（焊偏判定基准）检测：三材质分层 ----
    /// <summary>
    /// 孔位搜索区半径（× 焊环外半径）。焊环内部只有三种材质（暗缝隙 / 孔位端面 / 端面金属），
    /// 取 0.45 倍焊环外半径足以容纳它们，又不会把熔核本人卷进统计。
    ///
    /// 该区域只用焊环圆心与半径圈定，**不用孔位的任何先验**——焊环圆心与孔心的距离可达 97px
    /// （比孔半径还大），任何"以焊环圆心为起点向外找沿"的做法都会在孔沿被反光冲掉的一侧
    /// 越过孔位、落到熔核内沿上（实测把孔位半径量成 199px 而真值约 96px）。
    /// </summary>
    public double HoleSearchOuterRatio { get; set; } = 0.45;

    /// <summary>孔位半径下限（× 焊环外半径）。实测约 0.18（Img023 为 91.6/517）；不同端子尺寸不同，故只做宽区间校验。</summary>
    public double MinHoleRadiusRatio { get; set; } = 0.10;

    /// <summary>孔位半径上限（× 焊环外半径）。</summary>
    public double MaxHoleRadiusRatio { get; set; } = 0.40;

    /// <summary>孔位圆拟合残差上限（× 孔位半径）。残差大说明"中间灰度层"选到的不是那块圆盘。</summary>
    public double MaxHoleFitResidualRatio { get; set; } = 0.12;

    /// <summary>
    /// 孔位圆拟合残差的**绝对像素下限**（像素）；与 <see cref="MaxHoleFitResidualRatio"/> 取**较大者**生效。
    ///
    /// 为什么必须是绝对像素而不是相对量：拟合残差是**在工作分辨率上按像素算出来的**，而工作分辨率被
    /// <see cref="MaxWorkingBase"/> 限制在 460px——20MP 现场图（5472×3648）在这里被缩小 7.93 倍，
    /// 孔位圆盘的半径只剩下约 10.6px（= 0.023×base）。在这种尺寸下，掩码边界本身就是像素锯齿 +
    /// 灰度阈值在粗糙面上的切边，残差的**绝大部分来自分割边界的粗糙度**，而不是"这个形状偏离圆有多远"。
    /// 实测（tests/pp 20 个 SN / 300 帧，对所有进入闸门的 273 个中间层连通域统计）：
    ///   · 拟合半径 9.6~11.5px（中位 10.6）、半径/焊环半径 0.14~0.17（中位 0.15）——同一个物理孔位；
    ///   · 残差 0.64~3.55px（中位 1.81），而 <see cref="MaxHoleFitResidualRatio"/> 在此处只给出
    ///     0.12×10.6 = **1.27px** 的容差。
    /// 后果不是"精度略降"而是**孔位基准整体失效**：实测只有 17%~19% 的帧能过这道闸门，其余全部
    /// 退回梯度卡尺；而卡尺的射线原点是**焊环圆心**，孔心一旦偏离焊环圆心（本产品的实测偏离量
    /// 约 20 工作像素 ≈ 孔半径的 2 倍），"第一次上升沿"抓到的是熔核内沿——实测退回后报出的孔半径
    /// 中位 0.32×焊环半径，是真实孔位（0.15×焊环半径）的**两倍**，圆心偏离约 200 原始像素，
    /// 且偏移量被系统性**压低**（用户 2026-09-17 报的 OK_432 帧：算法报 0.324mm，孔位基准下为 0.94mm）。
    ///
    /// 取 4.0：略高于实测族群的最大残差 3.55px，即"不误杀任何实测的真孔位圆盘"；
    /// 同时相对项在大半径下仍然主导（0.12×R &gt; 4px ⟺ R &gt; 33px），换更大视野/更高工作分辨率时
    /// 本闸门不会失效。**判别"这块掩码是不是圆盘"的职责交给
    /// <see cref="HoleLocator"/> 里的圆度闸门（距离变换峰值半径 ÷ 等效半径 ≥ 0.6）**——
    /// 它只看内切圆峰值、不看逐个边界像素的残差，本身就是对边界粗糙度免疫的量，
    /// 实测它才是真正在筛掉非圆盘的东西（273 帧里 40 个被它拦下）。
    /// </summary>
    public double MinHoleFitResidualPx { get; set; } = 4.0;

    /// <summary>
    /// 三材质分层要求的最小灰度间距（灰阶）。暗缝隙 / 孔位端面 / 端面金属三层的相邻间距小于本值
    /// 就认为分层不可信（例如视野里只有两种材质），直接放弃孔位定位而不是硬给一个结果。
    ///
    /// 实测 Img023 三层约 100 / 192 / 255，相邻间距 60~90，取 12 留足余量。
    /// 用**相对间距**而不是绝对灰度值：曝光/增益变化时三层一起平移，判据不受影响。
    /// </summary>
    public double HoleMinClusterSeparation { get; set; } = 12.0;

    /// <summary>
    /// 孔位**外径**弧拟合（见 <see cref="Vision.HoleLocator"/> 的 FitOuterArc）的两个闸门。
    ///
    /// 背景：三材质分层取到的是孔位端面**被照亮的那一半**，阴影侧落在暗层里被排除，
    /// 因此中间层拟合半径只有真值的约 6 成（实测 OK_432 工作图 9.92px vs 真值 16.56px，
    /// 而两者圆心只差 0.75px——差的是半径，不是圆心）。半径偏小会连带压低估出的孔/环比、
    /// 并把熔核内沿的搜索起点（1.15×孔位半径）拖进孔内。
    /// 补法：孔位端面与端面金属（被反光冲白）之间有亮度台阶，是可见圆弧，用它拟合真实外径。
    /// 弧的搜索范围由 <see cref="MaxHoleRadiusRatio"/>×焊环半径给出（**不能用种子半径的倍数**：
    /// 种子在光照不利时只有真值的一半，实测会把真孔沿挡在搜索范围外，覆盖率 0/180）。
    ///
    /// <see cref="HoleOuterArcMinCoverageRatio"/>：弧覆盖的角向比例下限。实测 OK_432 覆盖约 180°
    ///   （两个约 112° 的扇区），取 0.25（90°）作为下限——低于此弧长对圆心/半径的约束不足。
    /// <see cref="HoleOuterArcResidualRatio"/>：弧拟合残差上限（× 弧半径）。实测 0.33px / 16.56px = 0.02，
    ///   取 0.15 留足余量；它拦的是"这条弧根本不是同一个圆"（熔核反光被误当边界）。
    ///
    /// 两项任一不满足即返回 null，由调用方按三态闸门退回中间层拟合；两者都不行才退回梯度卡尺。
    /// </summary>
    public double HoleOuterArcMinCoverageRatio { get; set; } = 0.25;

    /// <inheritdoc cref="HoleOuterArcMinCoverageRatio"/>
    public double HoleOuterArcResidualRatio { get; set; } = 0.15;

    // ---- 缺陷判定 ----
    /// <summary>环弧角度覆盖率下限（0~1）。未成环 = 未焊透/漏焊。良品实测恒为 1.00。</summary>
    public double MinRingCoverage { get; set; } = 0.75;

    /// <summary>焊环填充率下限（焊环面积 / πR²）。低于此值说明焊环残缺/未成形 → 漏焊。</summary>
    public double MinRingFill { get; set; } = 0.45;

    /// <summary>焊环填充率上限。高于此值说明熔融区远超正常环宽 → 炸焊。
    /// 良品实测 1.005±0.051，最大 1.088。刻意放宽到 1.35：宁可漏判炸焊，不可误判良品。</summary>
    public double MaxRingFill { get; set; } = 1.35;

    /// <summary>单个最大"暗孔"面积占比上限（孔面积 / πR²）。良品实测最大 0.076（那是固定阴影）。</summary>
    public double MaxPoreAreaRatio { get; set; } = 0.18;

    /// <summary>暗孔总面积占比上限（× πR²）。</summary>
    public double MaxPoreTotalRatio { get; set; } = 0.25;

    /// <summary>焊渣飞溅总面积上限（× base²）。良品实测 0.050±0.031，最大 0.180。</summary>
    public double MaxSpatterAreaRatio { get; set; } = 0.35;

    /// <summary>焊渣飞溅颗粒数上限。良品分布见 samples 统计。</summary>
    public int MaxSpatterCount { get; set; } = 20;

    /// <summary>飞溅颗粒的最小面积（× base²），用于滤除纹理噪声。</summary>
    public double MinSpatterBlobRatio { get; set; } = 0.00005;

    /// <summary>PLC 模拟轴运动耗时（毫秒），用于模拟 Stop-and-Go 节拍。</summary>
    public int PlcMoveTimeMs { get; set; } = 60;

    /// <summary>上位机轮询到位信号的间隔（毫秒）。</summary>
    public int ArrivalPollIntervalMs { get; set; } = 10;

    /// <summary>等待到位信号的超时（毫秒）。轴卡死/信号丢失时中止流程而非无限等待。</summary>
    public int ArrivalTimeoutMs { get; set; } = 10_000;

    /// <summary>单条 PLC 指令应答的超时（毫秒），用于检测通信断线。</summary>
    public int PlcResponseTimeoutMs { get; set; } = 5_000;
}
