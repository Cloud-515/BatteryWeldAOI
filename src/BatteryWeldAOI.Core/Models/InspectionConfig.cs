    ///
    /// 只对种子周围 <c>≈2.5×R</c> 的小 ROI 上采样，代价可忽略（约 550² 的 Sobel）。
    /// </summary>
    public int WeldRingRefineUpsample { get; set; } = 3;

    /// <summary>
    /// 精修的**边缘阈值比例**：径向中位剖面 g(r) 里，超过
    /// <c>本值 × 平台高度</c> 的样本算"仍有纹理"。平台高度取显著样本的
    /// <see cref="WeldRingRefinePlateauPercentile"/> 分位（不是剖面最大值）。
    ///
    /// ## 判据：ρ = 从内向外**第一段**显著平台的外端
    ///
    /// 这是本组参数的核心，也是 2026-09-18 这一轮修"红圈套在细圆上"的关键。
    /// 实测中位剖面（tests/pp 两帧，`|∇I|` 按角度取中位数，原图像素半径）：
    ///
    /// | 帧 | 平台 | 平滑区 | 细圈尖峰 |
    /// |---|---|---|---|
    /// | SN0067 第 0 帧（良品，有细圈） | 46~67 一直到 r≈467 | r≥499 恒 0 | 无（细圈与该圆心不同心，中位数抹掉） |
    /// | SN0002 第 10 帧（细圈被填洞成实心盘） | 37~80 一直到 r≈467 | **r 499~594 恒 0** | **r 626~658 中位 342** |
    ///
    /// 两帧的"熔核外沿"都在第一段平台的末端（r≈467，真值约 471~490）；第二帧 r≈640 的尖峰是
    /// 环形光源反射细圈。**旧判据取"最外侧仍显著半径"**，于是第二帧取到 658、第一帧取到边界带的
    /// 外沿，红圈整体外扩 30px 并把圆心带向细圈一侧——正是用户报的现象。
    ///
    /// 平台高度必须用**分位数**而不是剖面最大值：细圈尖峰 342 是熔核平台 67 的 5 倍，
